#!/usr/bin/env python3
# AP_FLAKE8_CLEAN
"""
Generate the CopterSonde launch pad and the Skycharge BOLOGNINI S1 models (CopterSonde-sim/models).

  cs_launch_pad          a 1.5 m square composite deck with yellow edge markings, 4 cm thick
  cs_skycharge_bolognini the BOLOGNINI S1 compact charging platform (6 x 6 steel tiles on a PVC
                         frame and aluminium legs) and its charge source box with the multicore cable

The pad's conductive area and its height are what the CopterSondePlugin uses to decide when the
CopterSonde's contact unit touches the tiles (<skycharge> in models/coptersonde/model.sdf), so keep
PAD_SIZE and PAD_TOP in step with it. The dimensions are estimates from Skycharge's photos and
specifications (a 6 x 6 tile compact platform that tolerates ~200 mm of landing error; the source
box is 410 x 315 x 150 mm, support.skycharge.de and skycharge.de/charging-system).
"""

import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = os.path.join(HERE, 'models')

DECK_SIZE = 1.50        # launch deck side (m)
DECK_H = 0.04           # deck thickness
PAD_SIZE = 0.60         # conductive area side
PAD_FRAME = 0.66        # PVC frame side
PAD_TOP = 0.12          # tile surface above the pad model origin (the deck top)
TILES = 6
TILE_GAP = 0.008
SOURCE_BOX = (0.410, 0.315, 0.150)


def mat(r, g, b, a=1.0, spec=0.1):
    return (f'<material><ambient>{r} {g} {b} {a}</ambient><diffuse>{r} {g} {b} {a}</diffuse>'
            f'<specular>{spec} {spec} {spec} 1</specular></material>')


def box(name, x, y, z, sx, sy, sz, color, collide=False):
    pose = f'<pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>'
    geo = f'<geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>'
    s = f'<visual name="{name}">{pose}{geo}{color}</visual>'
    if collide:
        s += f'<collision name="{name}_collision">{pose}{geo}</collision>'
    return s


def cyl(name, x, y, z, r, length, color, roll=0.0, pitch=0.0, yaw=0.0):
    return (f'<visual name="{name}"><pose>{x:.4f} {y:.4f} {z:.4f} {roll:.4f} {pitch:.4f} {yaw:.4f}</pose>'
            f'<geometry><cylinder><radius>{r}</radius><length>{length:.4f}</length></cylinder></geometry>'
            f'{color}</visual>')


def write_model(name, description, sdf_body):
    d = os.path.join(MODELS, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, 'model.config'), 'w') as f:
        f.write(f'''<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>{description}</description>
</model>
''')
    with open(os.path.join(d, 'model.sdf'), 'w') as f:
        f.write(f'''<?xml version="1.0"?>
<!-- Generated by CopterSonde-sim/tools/make_pad_models.py - edit the script, not this file. -->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="link">
{sdf_body}
    </link>
  </model>
</sdf>
''')


def launch_pad():
    deck = mat(0.22, 0.23, 0.25, spec=0.05)
    yellow = mat(0.95, 0.75, 0.05)
    white = mat(0.9, 0.9, 0.9)
    h = DECK_SIZE / 2
    parts = [box('deck', 0, 0, DECK_H / 2, DECK_SIZE, DECK_SIZE, DECK_H, deck, collide=True)]
    # yellow edge band and corner marks, white centre cross for the camera
    band, z = 0.06, DECK_H + 0.0005
    for i, (x, y, sx, sy) in enumerate(((0, h - band / 2, DECK_SIZE, band), (0, -h + band / 2, DECK_SIZE, band),
                                        (h - band / 2, 0, band, DECK_SIZE), (-h + band / 2, 0, band, DECK_SIZE))):
        parts.append(box(f'edge_{i}', x, y, z, sx, sy, 0.001, yellow))
    for i, (sx, sy) in enumerate(((1, 1), (1, -1), (-1, 1), (-1, -1))):
        parts.append(box(f'corner_{i}', sx * (h - 0.2), sy * (h - 0.2), z, 0.12, 0.12, 0.001, white))
    for i, (x, y) in enumerate(((0, h - 0.18), (0, -h + 0.18), (h - 0.18, 0), (-h + 0.18, 0))):
        parts.append(box(f'mark_{i}', x, y, z, 0.04 if x == 0 else 0.16, 0.16 if x == 0 else 0.04, 0.001, white))
    write_model('cs_launch_pad', 'CopterSonde launch deck (1.5 m) for the Skycharge BOLOGNINI S1.',
                '\n'.join('      ' + p for p in parts))


def bolognini():
    steel = mat(0.62, 0.63, 0.60, spec=0.6)
    pvc = mat(0.18, 0.19, 0.22)
    alu = mat(0.78, 0.79, 0.80, spec=0.5)
    grey = mat(0.70, 0.71, 0.70)
    black = mat(0.08, 0.08, 0.08)
    cable = mat(0.55, 0.57, 0.58)
    leg_h = PAD_TOP - 0.035
    parts = []
    # legs, frame plate (with the collision for the whole platform top) and the steel tiles
    for i, (sx, sy) in enumerate(((1, 1), (1, -1), (-1, 1), (-1, -1))):
        parts.append(box(f'leg_{i}', sx * (PAD_FRAME / 2 - 0.03), sy * (PAD_FRAME / 2 - 0.03), leg_h / 2,
                         0.04, 0.04, leg_h, alu))
        parts.append(cyl(f'foot_{i}', sx * (PAD_FRAME / 2 - 0.03), sy * (PAD_FRAME / 2 - 0.03), 0.004, 0.022,
                         0.008, black))
    parts.append(box('frame', 0, 0, leg_h + 0.015, PAD_FRAME, PAD_FRAME, 0.03, pvc))
    parts.append(f'<collision name="platform_collision"><pose>0 0 {PAD_TOP / 2:.4f} 0 0 0</pose>'
                 f'<geometry><box><size>{PAD_FRAME} {PAD_FRAME} {PAD_TOP}</size></box></geometry></collision>')
    pitch = PAD_SIZE / TILES
    for i in range(TILES):
        for j in range(TILES):
            x = -PAD_SIZE / 2 + (i + 0.5) * pitch
            y = -PAD_SIZE / 2 + (j + 0.5) * pitch
            parts.append(box(f'tile_{i}_{j}', x, y, PAD_TOP - 0.0025, pitch - TILE_GAP, pitch - TILE_GAP, 0.005, steel))
    # charge source box beside the platform, on the deck, and the multicore cable to the pad
    bx, by = 0.0, -(PAD_FRAME / 2 + 0.26)
    sx, sy, sz = SOURCE_BOX
    parts.append(box('source_box', bx, by, sz / 2, sx, sy, sz, grey, collide=True))
    parts.append(box('source_fan', bx - sx / 2 + 0.07, by + sy / 2 + 0.001, sz / 2, 0.09, 0.002, 0.09, black))
    parts.append(box('source_plug', bx + sx / 2 - 0.08, by + sy / 2 + 0.02, sz / 2, 0.07, 0.04, 0.06, grey))
    cy0, cy1 = by + sy / 2 + 0.04, -PAD_FRAME / 2
    parts.append(cyl('cable_run', bx + sx / 2 - 0.08, (cy0 + cy1) / 2, 0.012, 0.009, cy1 - cy0, cable,
                     roll=1.5708))
    parts.append(cyl('cable_rise', bx + sx / 2 - 0.08, cy1 + 0.02, leg_h / 2, 0.009, leg_h, cable))
    write_model('cs_skycharge_bolognini',
                'Skycharge BOLOGNINI S1 compact charging platform (6 x 6 tiles) with its charge source.',
                '\n'.join('      ' + p for p in parts))


if __name__ == '__main__':
    launch_pad()
    bolognini()
    print(f"models written to {MODELS}: cs_launch_pad (deck {DECK_SIZE} m), cs_skycharge_bolognini "
          f"(tiles {PAD_SIZE} m at {PAD_TOP} m)")
